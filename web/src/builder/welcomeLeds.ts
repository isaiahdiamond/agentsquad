const lineY = (p: Pt, x: number) => p[1] + ((VP[1] - p[1]) * (x - p[0])) / (VP[0] - p[0])

function seeded(seed: number) {
  return () => {
    seed = (seed + 0x6d2b79f5) | 0
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed)
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

// Racks the art fades out on, continued in perspective. In depth z = 1/k the visible racks repeat every ~0.16
// with faces ~0.08 deep, and the last one ends near z 1.65 on both walls.
export const DEEP_LEDS: Pt[] = (() => {
  const rnd = seeded(7)
  const out: Pt[] = []
  for (const wall of WALLS) {
    for (let z = 1.68; z < 3.1; z += 0.16) {
      for (const c of [0.15, 0.5, 0.85]) {
        const k = 1 / (z + 0.08 * c)
        const x = VP[0] + (wall.edge - VP[0]) * k
        const top = lineY(wall.top, x)
        const bottom = lineY(wall.bottom, x)
        for (let row = 0; row < 12; row++) {
          if (rnd() > 0.5 * Math.pow(1.68 / z, 1.5)) continue
          const u = 0.08 + (0.84 * (row + rnd() * 0.6)) / 12
          out.push([Math.round(x * 10) / 10, Math.round((top + (bottom - top) * u) * 10) / 10])
        }
      }
    }
  }
  return out
})()
